# 正整数排序：最长优先
_LEXICON_SORTED = sorted(LEXICON_EN, key=lambda p: len(p[0]), reverse=True)

# 完全匹配的枚举值缓存
_ENUM_PATTERN = re.compile("|".join(re.escape(k) for k in sorted(ENUM_VALUES_EN, key=len, reverse=True)))


def tr_value(value: str, lang: str = None) -> str:
    """将中文字段值翻译为展示值（默认当前语言；导出可显式指定语言）。

    英文模式下：
      1. 先查枚举精确映射（类别值：是/否/高/中/低/损伤类型等）
      2. 未命中的（自由文本）用词素最长匹配逐段替换，尽力而为；
         无法覆盖的字符保持原文。
    """
    if not value or value == "—":
        return value
    if (lang or LANG) != "en":
        return value
    if value in ENUM_VALUES_EN:
        return ENUM_VALUES_EN[value]

    # 多值枚举（如"涂层破损、腐蚀"）：按分隔符拆开逐个翻译
    parts = re.split(r"[、，,;；]", value)
    if len(parts) > 1 and all(p.strip() in ENUM_VALUES_EN for p in parts if p.strip()):
        return ", ".join(ENUM_VALUES_EN.get(p.strip(), p.strip()) for p in parts if p.strip())

    # 自由文本：词素替换（尽力而为）
    return _lexicon_replace(value)


def _lexicon_replace(text: str) -> str:
    """按最长优先词表替换文本。

    顿号分隔的并列成分（如"塔筒、叶片、机舱"）逐段翻译后用逗号连接，
    避免跨成分的误拼接；替换后在相邻译文之间补空格，保证可读性。
    """
    def _one(seg: str) -> str:
        out = seg
        for zh, en in _LEXICON_SORTED:
            if zh in out:
                out = out.replace(zh, f"\x00{en}\x00")
        # 相邻译文之间补空格
        out = re.sub(r"\x00\s*\x00", " ", out)
        out = out.replace("\x00", "")
        return out

    parts = re.split(r"([、，])", text)
    if len(parts) > 1:
        out_parts = []
        for p in parts:
            if p in ("、", "，"):
                out_parts.append(", ")
            else:
                out_parts.append(_one(p))
        out = "".join(out_parts)
    else:
        out = _one(text)
    # 全角括号/冒号转半角
    out = out.replace("（", " (").replace("）", ")").replace("：", ": ")
    out = re.sub(r"([A-Za-z])\(", r"\g<1> (", out)
    out = re.sub(r"\)([A-Za-z])", r") \g<1>", out)
    # 清理多余空格
    out = re.sub(r"\s+", " ", out).strip()
    out = re.sub(r"\s+([,.])", r"\g<1>", out)
    return out


def has_untranslated(text: str) -> bool:
    """检查翻译后文本是否仍含中文（未覆盖词）。"""
    return bool(re.search(r"[一-鿿]", text or ""))
