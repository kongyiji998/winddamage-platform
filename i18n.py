LANG = "zh"


def set_lang(lang: str):
    """设置全局语言（zh / en）。"""
    global LANG
    LANG = "en" if str(lang).lower().startswith("en") else "zh"


def detect_lang() -> str:
    """从命令行参数 / 环境变量检测语言，返回 'zh' 或 'en'。"""
    import sys
    if "--lang" in sys.argv:
        i = sys.argv.index("--lang")
        if i + 1 < len(sys.argv):
            return "en" if sys.argv[i + 1].lower().startswith("en") else "zh"
    env = os.environ.get("UI_LANG", "")
    return "en" if env.lower().startswith("en") else "zh"


